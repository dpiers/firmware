struct request {
	struct nlmsghdr h;
	union {
		struct ifaddrmsg addr;
		struct rtmsg route;
	}     u;
	char attrs[256];
};
static void attr(struct nlmsghdr *h, unsigned type, const void *data, size_t size)
{
	struct rtattr *a = (void *)((char *)h + NLMSG_ALIGN(h->nlmsg_len));
	a->rta_type = (unsigned short)type;
	a->rta_len = (unsigned short)RTA_LENGTH(size);
	memcpy(RTA_DATA(a), data, size);
	h->nlmsg_len = NLMSG_ALIGN(h->nlmsg_len) + RTA_ALIGN(a->rta_len);
}
static int nlsocket(void)
{
	int fd = socket(AF_NETLINK, SOCK_RAW | SOCK_CLOEXEC, NETLINK_ROUTE);
	struct sockaddr_nl sa = {.nl_family = AF_NETLINK};
	struct timeval timeout = {2, 0};
	if (fd < 0)
		return -1;
	if (bind(fd, (void *)&sa, sizeof(sa)) || setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &timeout, sizeof(timeout))) {
		close(fd);
		return -1;
	}
	return fd;
}
static int transact(struct request *r)
{
	int fd = nlsocket(), ret = -1;
	char data[8192];
	struct sockaddr_nl kernel = {.nl_family = AF_NETLINK};
	if (fd < 0)
		return -1;
	r->h.nlmsg_seq = 1;
	r->h.nlmsg_flags |= NLM_F_REQUEST | NLM_F_ACK;
	if (sendto(fd, r, r->h.nlmsg_len, 0, (void *)&kernel, sizeof(kernel)) != (ssize_t) r->h.nlmsg_len)
		goto out;
	for (;;) {
		ssize_t size = recv(fd, data, sizeof(data), MSG_TRUNC);
		if (size <= 0 || size > (ssize_t)sizeof(data))
			break;
		for (struct nlmsghdr *h = (void *)data; NLMSG_OK(h, size); h = NLMSG_NEXT(h, size)) {
			if (h->nlmsg_seq != 1)
				continue;
			if (h->nlmsg_type == NLMSG_ERROR && h->nlmsg_len >= NLMSG_LENGTH(sizeof(struct nlmsgerr))) {
				struct nlmsgerr *e = NLMSG_DATA(h);
				ret = e->error;
				goto out;
			}
		}
	}
out:	close(fd);
	return ret;
}
/* Count selected IPv4 objects; exact=true restricts to our recorded tuple. */
static int objects(struct wifi_net *n, bool route, bool exact)
{
	struct request q = {0};
	struct sockaddr_nl kernel = {.nl_family = AF_NETLINK};
	char data[32768];
	int fd = nlsocket(), count = 0, candidates = 0;
	if (fd < 0)
		return -2;
	q.h.nlmsg_len = route ? NLMSG_LENGTH(sizeof(struct rtmsg)) : NLMSG_LENGTH(sizeof(struct ifaddrmsg));
	q.h.nlmsg_type = route ? RTM_GETROUTE : RTM_GETADDR;
	q.h.nlmsg_flags = NLM_F_REQUEST | NLM_F_DUMP;
	q.h.nlmsg_seq = 1;
	if (route)
		q.u.route.rtm_family = AF_INET;
	else
		q.u.addr.ifa_family = AF_INET;
	if (sendto(fd, &q, q.h.nlmsg_len, 0, (void *)&kernel, sizeof(kernel)) != (ssize_t) q.h.nlmsg_len) {
		count = -2;
		goto out;
	}
	for (;;) {
		ssize_t size = recv(fd, data, sizeof(data), MSG_TRUNC);
		if (size <= 0 || size > (ssize_t)sizeof(data)) {
			count = -2;
			break;
		}
		for (struct nlmsghdr *h = (void *)data; NLMSG_OK(h, size); h = NLMSG_NEXT(h, size)) {
			if (h->nlmsg_seq != 1)
				continue;
			if (h->nlmsg_flags & NLM_F_DUMP_INTR) {
				count = -2;
				goto out;
			}
			if (h->nlmsg_type == NLMSG_DONE) {
				if (h->nlmsg_len >= NLMSG_LENGTH(sizeof(int))) {
					int error;
					memcpy(&error, NLMSG_DATA(h), sizeof(error));
					if (error)
						count = -2;
				}
				if (exact && !count && candidates)
					count = -1;
				goto out;
			}
			if (h->nlmsg_type == NLMSG_ERROR) {
				count = -2;
				goto out;
			}
			if (route && h->nlmsg_type == RTM_NEWROUTE) {
				if (h->nlmsg_len < NLMSG_LENGTH(sizeof(struct rtmsg))) {
					count = -2;
					goto out;
				}
				struct rtmsg *m = NLMSG_DATA(h);
				unsigned oif = 0, metric = 0, table = m->rtm_table;
				uint32_t gateway = 0;
				int len = RTM_PAYLOAD(h);
				for (struct rtattr *a = RTM_RTA(m); RTA_OK(a, len); a = RTA_NEXT(a, len)) {
					if (RTA_PAYLOAD(a) != 4)
						continue;
					if (a->rta_type == RTA_TABLE)
						memcpy(&table, RTA_DATA(a), 4);
					if (a->rta_type == RTA_OIF)
						memcpy(&oif, RTA_DATA(a), 4);
					if (a->rta_type == RTA_GATEWAY)
						memcpy(&gateway, RTA_DATA(a), 4);
					if (a->rta_type == RTA_PRIORITY)
						memcpy(&metric, RTA_DATA(a), 4);
				}
				if (len) {
					count = -2;
					goto out;
				}
				if (oif == n->ifindex) {
					/* Connected/local routes can be generated by our address. */
					if (!m->rtm_dst_len)
						candidates++;
					if (!exact || (m->rtm_family == AF_INET && !m->rtm_dst_len &&
					    !m->rtm_src_len && !m->rtm_tos && table == RT_TABLE_MAIN &&
					    m->rtm_type == RTN_UNICAST && m->rtm_scope == RT_SCOPE_UNIVERSE &&
					    m->rtm_protocol == RTPROT_STATIC && gateway == n->lease.router && metric == 32760))
						count++;
				}
			} else if (!route && h->nlmsg_type == RTM_NEWADDR) {
				if (h->nlmsg_len < NLMSG_LENGTH(sizeof(struct ifaddrmsg))) {
					count = -2;
					goto out;
				}
				struct ifaddrmsg *m = NLMSG_DATA(h);
				uint32_t local = 0, peer = 0;
				int len = IFA_PAYLOAD(h);
				for (struct rtattr *a = IFA_RTA(m); RTA_OK(a, len); a = RTA_NEXT(a, len)) {
					if (a->rta_type == IFA_LOCAL && RTA_PAYLOAD(a) == 4)
						memcpy(&local, RTA_DATA(a), 4);
					if (a->rta_type == IFA_ADDRESS && RTA_PAYLOAD(a) == 4)
						memcpy(&peer, RTA_DATA(a), 4);
				}
				if (len) {
					count = -2;
					goto out;
				}
				unsigned prefix = (unsigned)__builtin_popcount(ntohl(n->lease.mask));
				if (m->ifa_index == n->ifindex) {
					candidates++;
					if (!exact || (m->ifa_family == AF_INET && m->ifa_scope == RT_SCOPE_UNIVERSE &&
					    local == n->lease.address && peer == local && m->ifa_prefixlen == prefix))
						count++;
				}
			}
		}
		if (size) {
			count = -2;
			break;
		}
	}
out:	close(fd);
	return count;
}
static int address(struct wifi_net *n, bool add)
{
	struct request q = {0};
	q.h.nlmsg_len = NLMSG_LENGTH(sizeof(struct ifaddrmsg));
	q.h.nlmsg_type = add ? RTM_NEWADDR : RTM_DELADDR;
	q.h.nlmsg_flags = add ? NLM_F_CREATE | NLM_F_EXCL : 0;
	q.u.addr.ifa_family = AF_INET;
	q.u.addr.ifa_index = n->ifindex;
	q.u.addr.ifa_prefixlen = (unsigned char)__builtin_popcount(ntohl(n->lease.mask));
	attr(&q.h, IFA_LOCAL, &n->lease.address, 4);
	attr(&q.h, IFA_ADDRESS, &n->lease.address, 4);
	return transact(&q);
}
static int route(struct wifi_net *n, bool add)
{
	struct request q = {0};
	unsigned metric = 32760;
	q.h.nlmsg_len = NLMSG_LENGTH(sizeof(struct rtmsg));
	q.h.nlmsg_type = add ? RTM_NEWROUTE : RTM_DELROUTE;
	q.h.nlmsg_flags = add ? NLM_F_CREATE | NLM_F_EXCL : 0;
	q.u.route.rtm_family = AF_INET;
	q.u.route.rtm_table = RT_TABLE_MAIN;
	q.u.route.rtm_protocol = RTPROT_STATIC;
	q.u.route.rtm_type = RTN_UNICAST;
	q.u.route.rtm_scope = RT_SCOPE_UNIVERSE;
	attr(&q.h, RTA_OIF, &n->ifindex, 4);
	attr(&q.h, RTA_GATEWAY, &n->lease.router, 4);
	attr(&q.h, RTA_PRIORITY, &metric, 4);
	return transact(&q);
}
static int flags(struct wifi_net *n, bool up, bool change)
{
	int fd = socket(AF_INET, SOCK_DGRAM | SOCK_CLOEXEC, 0);
	struct ifreq r = {0};
	if (fd < 0)
		return -1;
	strcpy(r.ifr_name, n->interface);
	int ret = ioctl(fd, SIOCGIFFLAGS, &r);
	if (!ret && change) {
		if (up)
			r.ifr_flags |= IFF_UP;
		else
			r.ifr_flags &= ~IFF_UP;
		ret = ioctl(fd, SIOCSIFFLAGS, &r);
	} else if (!ret)
		ret = (r.ifr_flags & IFF_UP) != 0;
	close(fd);
	return ret;
}
static int text(const char *path, char *buf, size_t size)
{
	int fd = open(path, O_RDONLY | O_CLOEXEC);
	if (fd < 0)
		return -1;
	ssize_t n = read(fd, buf, size - 1);
	close(fd);
	if (n < 0)
		return -1;
	buf[n] = 0;
	return 0;
}
int wifi_net_admit(struct wifi_net *n, const char *name)
{
	char path[256], data[4096], real[4096];
	memset(n, 0, sizeof(*n));
	n->resolver_dir = -1;
	strcpy(n->interface, name);
	n->ifindex = if_nametoindex(name);
	if (!n->ifindex)
		return -1;
	snprintf(path, sizeof(path), "/sys/class/net/%s/device/driver", name);
	if (!realpath(path, real) || strcmp(strrchr(real, '/') + 1, "rtl8xxxu"))
		return -1;
	snprintf(path, sizeof(path), "/sys/class/net/%s/device/../idVendor", name);
	if (text(path, data, sizeof(data)) || strcmp(data, "0bda\n"))
		return -1;
	snprintf(path, sizeof(path), "/sys/class/net/%s/device/../idProduct", name);
	if (text(path, data, sizeof(data)) || strcmp(data, "f179\n"))
		return -1;
	snprintf(path, sizeof(path), "/proc/sys/net/ipv6/conf/%s/disable_ipv6", name);
	if (text(path, data, sizeof(data))) {
		if (access("/proc/sys/net/ipv6", F_OK) == 0)
			return -1;
	} else if (strcmp(data, "1\n"))
		return -1;
	if (objects(n, false, false) != 0 || objects(n, true, false) != 0)
		return -1;
	if (wifi_resolver_open(n, "/etc/resolv.conf"))
		return -1;
	int up = flags(n, false, false);
	if (up < 0)
		return -1;
	if (!up) {
		if (flags(n, true, true))
			return -1;
		n->raised = true;
	}
	return 0;
}
int wifi_net_clear(struct wifi_net *n)
{
	int ret = wifi_resolver_clear(n);
	int routes = n->route ? objects(n, true, true) : 0;
	int addresses = n->address ? objects(n, false, true) : 0;
	if (routes < -1 || addresses < -1)
		return -1;
	if (if_nametoindex(n->interface) != n->ifindex) {
		n->route = n->address = false;
		return ret;
	}
	if (n->route) {
		int count = routes;
		if (count < 0 || (count && route(n, false)))
			ret = -1;
		else
			n->route = false;
	}
	if (n->address) {
		int count = addresses;
		if (count < 0 || (count && address(n, false)))
			ret = -1;
		else
			n->address = false;
	}
	return ret;
}
int wifi_net_apply(struct wifi_net *n, const struct wifi_lease *l)
{
	if (n->address && n->dns_owned && n->route == (l->router != 0) &&
	    !memcmp(&n->lease, l, offsetof(struct wifi_lease, seconds))) {
		if (if_nametoindex(n->interface) != n->ifindex || objects(n, false, true) != 1 ||
		    (n->route && objects(n, true, true) != 1))
			return -1;
		return wifi_resolver_set(n, l);
	}
	if (if_nametoindex(n->interface) != n->ifindex || wifi_net_clear(n))
		return -1;
	n->lease = *l;
	if (address(n, true))
		return -1;
	n->address = true;
	if (l->router) {
		if (route(n, true))
			goto fail;
		n->route = true;
	}
	if (wifi_resolver_set(n, l))
		goto fail;
	return 0;
fail:	wifi_net_clear(n);
	return -1;
}
int wifi_net_close(struct wifi_net *n)
{
	int ret = wifi_net_clear(n);
	if (n->raised && if_nametoindex(n->interface) == n->ifindex)
		if (flags(n, false, true))
			ret = -1;
	if (n->resolver_dir >= 0)
		close(n->resolver_dir);
	free(n->baseline);
	free(n->expected);
	n->baseline = n->expected = NULL;
	return ret;
}
